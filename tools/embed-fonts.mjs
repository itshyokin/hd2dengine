/**
 * Writes src/fonts.css: the game's and editor's fonts as data URLs, so they work offline (Steam / desktop builds,
 * pages opened as files) with nothing fetched from the internet. Run after changing public/fonts:
 *   bun tools/embed-fonts.mjs
 *
 * All four are under the SIL Open Font License 1.1 (each folder has its OFL.txt): free to bundle in a commercial
 * game; the fonts themselves can't be sold on their own.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const face = (family, file, weight = '400', extra = '') => {
  const b64 = readFileSync(path.join(root, 'public/fonts', file)).toString('base64');
  return `@font-face { font-family: "${family}"; src: url(data:font/ttf;base64,${b64}) format("truetype"); font-weight: ${weight}; font-style: normal; font-display: block;${extra} }`;
};
const css = [
  '/* Generated by tools/embed-fonts.mjs from public/fonts (SIL Open Font License 1.1). Do not edit by hand. */',
  // Pixel fonts for the game. "Press Start 2P" is drawn on an 8 px grid and is wide: shrunk to sit in the same
  // sizes as the rest of the UI (13 px text comes out at 8 px, 26 px at 16 px, sharp).
  face('Game Pixel', 'pressstart2p/PressStart2P-Regular.ttf', '100 900', ' size-adjust: 61.54%;'),
  face('Game Pixel Soft', 'pixelifysans/PixelifySans.ttf', '400 700', ' size-adjust: 112%;'),
  face('Silkscreen', 'silkscreen/Silkscreen-Regular.ttf', '400'),
  face('Silkscreen', 'silkscreen/Silkscreen-Bold.ttf', '700'),
  face('Atkinson Hyperlegible', 'atkinsonhyperlegible/AtkinsonHyperlegible-Regular.ttf', '400'),
  face('Atkinson Hyperlegible', 'atkinsonhyperlegible/AtkinsonHyperlegible-Bold.ttf', '700'),
].join('\n') + '\n';
writeFileSync(path.join(root, 'src/fonts.css'), css);
console.log(`Wrote src/fonts.css (${Math.round(css.length / 1024)} KB)`);
